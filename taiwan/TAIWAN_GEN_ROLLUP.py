"""
Taiwan generation by fuel, rolled up from 10-minute data to DAILY and MONTHLY series
(output/Data and Chart Outputs/taiwan_generation_rollup.xlsx). Two separate series, never mixed in one table:

  Daily Zenodo / Monthly Zenodo
      Taipower's 'Electricity generated by each unit in the past' (data.gov.tw 37331) as published on Zenodo
      (doi 10.5281/zenodo.7537890, Fu and Chen, licence CC BY 4.0; underlying data under Taiwan's Open Government Data
      License v1.0): 10-minute MW by type, Jan 2017 - 1 Jul 2022, Taipower's EMS units PLUS the independent power
      producers (ippLng, ippCoal) and cogeneration. Downloaded once (checksum verified) and rolled up; the stored sheets
      are the history after that. Not a Taipower or government publication in this form: a third-party copy.
  Daily EMS / Monthly EMS
      The same dataset's current files from Taipower (service.taipower.com.tw .../d006010/001.json: a rolling
      three-month window, replaced monthly, ending about three months back) and the older windows that the Internet
      Archive (web.archive.org) holds copies of. EMS-dispatched Taipower units ONLY: no IPPs, almost no solar or wind
      (about half of national generation). Each window is ingested once (sheet 'Windows'); a window that the archive
      copy truncated (no closing brackets) is recorded as failed and not used.
  Coverage
      Each series against the Energy Administration's national generation by fuel (E-STAT, taiwan_esist_monthly.xlsx),
      annual for Zenodo years and monthly for EMS months, for periods with >= 90% of 10-minute intervals.

Roll-up rules (no scaling, no filling): DAILY = sum over present 10-minute intervals of MW x 10/60 h (MWh) by fuel, the
number of distinct 10-minute stamps present (n_intervals, 144 = full day) and the average GW over the PRESENT intervals;
a day with fewer than 130 of 144 intervals (< 90%) is flagged (complete = 0) and left out of charts. MONTHLY = the same
sums over the month, coverage_pct = intervals present / (days x 144); charted only when >= 90%. Duplicate (unit, stamp)
records are counted once; Zenodo readings stamped off the 10-minute grid (335 of 280,625, mostly 2017) are put in the slot they
fall in and only the first reading of a slot is kept. Pumped storage is generation only (E-STAT also counts pumped-storage output in its total).

    python3 taiwan/TAIWAN_GEN_ROLLUP.py --out "output/Data and Chart Outputs/taiwan_generation_rollup.xlsx"
"""
